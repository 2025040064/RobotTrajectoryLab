function build_installer_only()
%BUILD_INSTALLER_ONLY Install the GUI launcher, MATLAB core, manuals and Runtime.
root=fileparts(fileparts(mfilename('fullpath')));
stage=fullfile(root,'build','installer_stage');
output=fullfile(root,'dist','RobotTrajectoryLab_安装程序与文档');
if ~isfolder(output), mkdir(output); end
files={fullfile(stage,'RobotTrajectoryLab.exe'),fullfile(stage,'app'), ...
    fullfile(stage,'使用说明.pdf'),fullfile(stage,'技术要点与创新点.pdf')};
opts=compiler.package.InstallerOptions('ApplicationName','RobotTrajectoryLab', ...
    'AuthorName','Astrspire','Version','1.0.1', ...
    'InstallerName','RobotTrajectoryLab_Setup','OutputDir',output, ...
    'RuntimeDelivery','web','OptionalDependencies','none', ...
    'Shortcut',fullfile(stage,'RobotTrajectoryLab.exe'), ...
    'Summary','MATLAB robot trajectory planning and simulation', ...
    'InstallationNotes','Uses MATLAB Runtime R2025a. The GUI launcher finds the installed Runtime automatically. User data is stored in USERPROFILE/RobotTrajectoryLab_Data.', ...
    'Verbose','on');
compiler.package.installer(files,fullfile(root,'build','standalone','buildresult.json'),'Options',opts);
copyfile(fullfile(stage,'使用说明.pdf'),fullfile(output,'使用说明.pdf'));
copyfile(fullfile(stage,'技术要点与创新点.pdf'),fullfile(output,'技术要点与创新点.pdf'));
fprintf('INSTALLER_AND_DOCUMENTS_READY\n');
end
