function build_release(options)
%BUILD_RELEASE Build the existing V1.0 application with MATLAB Compiler.
arguments
    options.Installer (1,1) logical = true
end
root=fileparts(mfilename('fullpath')); addpath(root);
buildDir=fullfile(root,'build','standalone');
distDir=fullfile(root,'dist');
modelDir=fullfile(root,'assets','models');
if ~isfolder(modelDir), mkdir(modelDir); end
if ~isfolder(distDir), mkdir(distDir); end
robot=loadrobot('universalUR5','DataFormat','row','Gravity',[0 0 -9.81]);
save(fullfile(modelDir,'universalUR5.mat'),'robot');
fprintf('Building RobotTrajectoryLab 1.0.1 with %s\n',version);
results=compiler.build.standaloneWindowsApplication(fullfile(root,'RobotTrajectoryLab.m'), ...
    'AdditionalFiles',{fullfile(root,'assets'),fullfile(root,'+rtl')}, ...
    'AutoDetectDataFiles','on','ExecutableName','RobotTrajectoryLab', ...
    'ExecutableVersion','1.0.1','ExecutableSplashScreen',fullfile(root,'assets','startup.png'), ...
    'OutputDir',buildDir,'Verbose','on');
save(fullfile(root,'build','compiler_results.mat'),'results');
runtime=struct('required',table2struct(results.RuntimeDependencies.Required), ...
    'optional',table2struct(results.RuntimeDependencies.Optional), ...
    'selectedOptionalDependencies','none');
fid=fopen(fullfile(root,'build','runtime_dependencies.json'),'w','n','UTF-8');
cleanup=onCleanup(@()fclose(fid)); fprintf(fid,'%s',jsonencode(runtime,'PrettyPrint',true)); clear cleanup
if options.Installer
    opts=compiler.package.InstallerOptions(results, ...
        'ApplicationName','RobotTrajectoryLab','AuthorName','Astrspire', ...
        'Version','1.0.1','InstallerName','RobotTrajectoryLab_Setup', ...
        'OutputDir',fullfile(distDir,'installer_v101'),'RuntimeDelivery','web', ...
        'OptionalDependencies','none', ...
        'Summary','UR5 trajectory and mobile robot A-star simulation', ...
        'InstallationNotes','Requires MATLAB Runtime R2025a for Windows x64. Runtime is downloaded during installation.', ...
        'Verbose','on');
    compiler.package.installer(results,'Options',opts);
end
fprintf('BUILD_COMPLETE: %s\n',buildDir);
end
