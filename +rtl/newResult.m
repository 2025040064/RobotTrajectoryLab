function result = newResult(request)
%NEWRESULT 所有规划器使用相同的可持久化结果外壳。
stamp = datetime('now','TimeZone','UTC','Format','yyyyMMdd_HHmmss_SSS');
[~,token] = fileparts(tempname);
result = struct('schemaVersion',1,'id',[char(stamp) '_' token], ...
    'kind',request.kind,'algorithm',request.algorithm,'status','error', ...
    'message','','request',request,'createdAt',char(stamp), ...
    'softwareVersion','1.0.1','matlabRelease',version('-release'), ...
    'rawPath',[],'finalPath',[],'trajectory',struct(), ...
    'baseline',struct(),'metrics',struct(),'constraints',struct(), ...
    'collision',struct(),'diagnostics',{{}},'environment',rtl.io.environmentInfo());
end
